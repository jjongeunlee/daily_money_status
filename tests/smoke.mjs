import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, headless: true })
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(process.env.TEST_URL || 'http://localhost:4173')
  await page.getByRole('button', { name: '예산 수정' }).click()
  await page.getByLabel('식비 (원)').fill('600000')
  await page.getByRole('button', { name: '예산 저장' }).click()
  await page.getByRole('button', { name: '＋ 지출 기록', exact: true }).filter({ visible: true }).click()
  await page.getByLabel('금액 (원)').fill('15000')
  await page.getByLabel('메모').fill('점심')
  await page.getByRole('button', { name: '기록 저장' }).click()
  await page.getByText('점심', { exact: true }).waitFor()
  assert.match(await page.locator('.balance h2').innerText(), /1,685,000/)
  await page.getByRole('button', { name: '＋ 지출 기록', exact: true }).filter({ visible: true }).click()
  await page.getByLabel('금액 (원)').fill('1000000')
  await page.getByLabel('메모').fill('가전')
  await page.getByLabel('큰 지출로 기록').check()
  await page.getByRole('button', { name: '기록 저장' }).click()
  await page.getByText('가전', { exact: true }).waitFor()
  assert.match(await page.locator('.balance h2').innerText(), /1,685,000/)
  assert.match(await page.locator('.large-card > strong').innerText(), /1,000,000/)
  await page.reload()
  await page.getByText('점심', { exact: true }).waitFor()
  assert.match(await page.locator('.balance h2').innerText(), /1,685,000/)
  await page.getByRole('button', { name: '이전 달' }).click()
  assert.match(await page.locator('.balance h2').innerText(), /1,600,000/)
  await page.getByRole('button', { name: '다음 달' }).click()
  await page.getByText('점심', { exact: true }).waitFor()
  const beforeEdit = await page.evaluate(() => JSON.parse(localStorage.getItem('daily-money:v1')))
  await page.getByRole('button', { name: '점심 15,000원 수정', exact: true }).click()
  assert.equal(await page.getByLabel('금액 (원)').inputValue(), '15000')
  await page.getByLabel('금액 (원)').fill('18000')
  await page.getByLabel('메모').fill('점심 수정')
  await page.getByRole('button', { name: '수정 저장', exact: true }).click()
  await page.getByRole('button', { name: '점심 수정 18,000원 수정', exact: true }).waitFor()
  const afterEdit = await page.evaluate(() => JSON.parse(localStorage.getItem('daily-money:v1')))
  assert.equal(afterEdit.expenses.length, beforeEdit.expenses.length)
  assert.equal(afterEdit.expenses[0].id, beforeEdit.expenses[0].id)
  assert.deepEqual(afterEdit.expenses[1], beforeEdit.expenses[1])
  assert.deepEqual(afterEdit.budgets, beforeEdit.budgets)
  assert.match(await page.locator('.balance h2').innerText(), /1,682,000/)
  await page.reload()
  await page.getByRole('button', { name: '점심 수정 18,000원 수정', exact: true }).click()
  await page.getByLabel('금액 (원)').fill('15000')
  await page.getByLabel('메모').fill('점심')
  await page.getByRole('button', { name: '수정 저장', exact: true }).click()
  await page.getByRole('button', { name: '점심 15,000원 수정', exact: true }).waitFor()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '점심 15,000원 삭제' }).click()
  await page.getByText('점심', { exact: true }).waitFor({ state: 'detached' })
  assert.match(await page.locator('.balance h2').innerText(), /1,700,000/)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: '/tmp/daily-money-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: '/tmp/daily-money-desktop.png', fullPage: true })
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: '백업 파일 저장', exact: true }).click()
  const download = await downloadEvent
  const backupPath = '/tmp/daily-money-test-backup.json'
  await download.saveAs(backupPath)
  const { readFile } = await import('node:fs/promises')
  const backup = JSON.parse(await readFile(backupPath, 'utf8'))
  assert.equal(backup.data.expenses.length, 1)
  assert.equal(Object.values(backup.data.budgets)[0]['식비'], 600000)
  await page.locator('input[type=file]').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{bad') })
  await page.getByRole('alert').waitFor()
  assert.match(await page.locator('.balance h2').innerText(), /1,700,000/)
  await page.locator('input[type=file]').setInputFiles(backupPath)
  await page.getByRole('button', { name: '취소', exact: true }).click()
  assert.match(await page.locator('.balance h2').innerText(), /1,700,000/)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '가전 1,000,000원 삭제' }).click()
  await page.getByText('가전', { exact: true }).waitFor({ state: 'detached' })
  await page.locator('input[type=file]').setInputFiles(backupPath)
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('quota') } })
  await page.getByRole('button', { name: '전체 기록 교체하고 복원' }).click()
  await page.getByRole('alert').waitFor()
  assert.equal(await page.getByText('가전', { exact: true }).count(), 0)
  await page.reload()
  await page.locator('input[type=file]').setInputFiles(backupPath)
  await page.getByRole('button', { name: '전체 기록 교체하고 복원' }).click()
  await page.getByText('가전', { exact: true }).waitFor()
  await page.reload()
  await page.getByText('가전', { exact: true }).waitFor()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload()
  await page.getByText('가전', { exact: true }).waitFor()
  await context.setOffline(true)
  await page.reload()
  await page.getByText('가전', { exact: true }).waitFor()
  assert.match(await page.locator('.balance h2').innerText(), /1,700,000/)
  assert.deepEqual(errors, [])
  console.log('PASS: budget editing, expenses, large-expense exclusion, persistence, monthly isolation, deletion, mobile/desktop layout, backup download/restore/cancel/invalid-file/storage-failure, offline reload')
} finally { await browser.close() }
